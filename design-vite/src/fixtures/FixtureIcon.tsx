interface FixtureIconProps {
  readonly iconId: string;
  readonly svgProps: LucideProps;
}

export function FixtureIcon({ iconId, svgProps }: FixtureIconProps): React.JSX.Element {
  const Icon = ICON_BY_ID[iconId];
  if (!Icon) throw new Error(`Unknown fixture icon: ${iconId}`);
  return <Icon {...svgProps} data-fixture-node="" />;
}